"""Generate a checked C ABI adapter from the upstream Kotlin declarations."""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent
source = (root.parent / 'app/src/main/kotlin/com/compose/sctool/ScProcessor.kt').read_text()
declarations = []
dispatch = []
for name, params in re.findall(r'external fun (native\w+)\((.*?)\): String', source):
    if name == 'nativeDowngrade':
        continue  # Upstream ships an Android ELF binary, without source.
    types = [p.strip().split(':')[1].strip() for p in params.split(',') if p.strip()]
    assert all(t in ('String', 'Int') for t in types), (name, types)
    symbol = 'Java_com_compose_sctool_ScProcessor_' + name
    declarations.append('extern "C" jstring ' + symbol + '(JNIEnv*, jclass, ' + ', '.join('jint' if t == 'Int' else 'jstring' for t in types) + ');')
    args = ', '.join(f'number(argv[{i}])' if t == 'Int' else f'argv[{i}]' for i, t in enumerate(types))
    dispatch.append(f'        if (op == "{name}") {{ if (argc != {len(types)}) throw std::invalid_argument("Wrong argument count"); return copy({symbol}(&env, nullptr, {args})); }}')

body = '''// Generated by ios/generate_bridge.py. Keep upstream operations in sync.
#include "QwCore.h"
#include <jni.h>
#include <string>
#include <cstring>
#include <cstdlib>
#include <stdexcept>
#include <mutex>
'''
body += '\n'.join(declarations)
body += '''
static char* copy(const char* text) {
    if (!text) text = "Error: empty native result";
    return strdup(text);
}
static int number(const char* value) {
    size_t consumed = 0;
    int result = std::stoi(value, &consumed);
    if (consumed != std::strlen(value)) throw std::invalid_argument("Invalid number");
    return result;
}
extern "C" void qw_free(char* result) { std::free(result); }
extern "C" char* qw_run(const char* operation, int argc, const char* const* argv) {
    // Upstream uses process-global caches in a few tools: serialize all entry points.
    static std::mutex mutex;
    std::lock_guard<std::mutex> guard(mutex);
    try {
        if (!operation || argc < 0 || (argc && !argv)) throw std::invalid_argument("Missing arguments");
        for (int i = 0; i < argc; ++i) if (!argv[i]) throw std::invalid_argument("Null argument");
        JNIEnv env;
        std::string op(operation);
'''
body += '\n'.join(dispatch)
body += '''
        return copy("Error: operation is not available on iOS");
    } catch (const std::exception& e) {
        return copy((std::string("Error: ") + e.what()).c_str());
    } catch (...) {
        return copy("Error: unexpected native exception");
    }
}
'''
(root / 'Native/QwCore.cpp').write_text(body)
print(f'Generated {len(dispatch)} operations')
